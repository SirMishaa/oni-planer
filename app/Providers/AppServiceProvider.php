<?php

declare(strict_types=1);

namespace App\Providers;

use App\Ai\ClaudeCode\ClaudeCodeProvider;
use App\Ai\ClaudeCode\ClaudeCodeRunRecorder;
use App\Services\Critters\CritterDietRepository;
use App\Services\Critters\EloquentCritterDietRepository;
use App\Services\Critters\OccupancyInputBuilder;
use App\Services\GameText;
use Illuminate\Foundation\DevCommands;
use Illuminate\Support\ServiceProvider;
use Laravel\Ai\AiManager;

final class AppServiceProvider extends ServiceProvider
{
    public function register(): void
    {
        $this->app->scoped(GameText::class);
        $this->app->scoped(ClaudeCodeRunRecorder::class);
        $this->app->scoped(OccupancyInputBuilder::class);
        $this->app->scoped(CritterDietRepository::class, EloquentCritterDietRepository::class);
    }

    public function boot(): void
    {
        // Game string catalogs (STRINGS.* keys) generated by `game:import`.
        $this->app->make('translator')->addJsonPath(lang_path('game'));
        $this->callAfterResolving(AiManager::class, function (AiManager $manager): void {
            $manager->extend('claude-code', fn ($app, array $config): ClaudeCodeProvider => new ClaudeCodeProvider($config, $app['events']));
        });

        $isPreviewServer = config('game.preview_server', false);

        if (app()->isLocal()) {
            $serverCommand = 'php artisan octane:start --watch --server=frankenphp --port=8003 --caddyfile=Caddyfile';

            if ($isPreviewServer) {
                $serverCommand = 'NODE_ENV=production bun run build && rm -f '.escapeshellarg(public_path('hot')).' && '.$serverCommand;
                DevCommands::except('vite');
            }

            DevCommands::register(self::teeToLog($serverCommand, 'server'), 'server')->blue();
            DevCommands::register(self::teeToLog('php artisan reverb:start --debug', 'reverb'), 'reverb')->purple();
            // Uplink messages land on their own queues (UplinkMessageType::queue()): reliable ones in order on one worker, states on another.
            DevCommands::register(self::teeToLog(self::workerLoop('uplink-reliable'), 'queue-reliable'), 'reliable')->yellow();
            DevCommands::register(self::teeToLog(self::workerLoop('uplink-state,default'), 'queue-state'), 'state')->yellow();
            DevCommands::artisan('pail --timeout=0', 'logs')->orange();
            if (! $isPreviewServer) {
                DevCommands::register(self::teeToLog('bun run dev', 'vite'), 'vite')->green();
            }
        }
    }

    /**
     * A long-lived worker (one boot for every job, unlike queue:listen) started again whenever it
     * exits, so `php artisan queue:restart` loads changed PHP code.
     */
    private static function workerLoop(string $queues): string
    {
        return "while true; do php artisan queue:work redis --queue={$queues} --tries=1 --sleep=0.1 --timeout=0; sleep 1; done";
    }

    /**
     * Wraps a dev command so its output also lands in storage/logs/dev/{name}.log, where tools
     * that cannot see the `php artisan dev` terminal can read it. pipefail keeps the command's
     * exit code, so the dev runner still restarts it on a crash.
     */
    private static function teeToLog(string $command, string $name): string
    {
        $logFile = escapeshellarg(storage_path("logs/dev/{$name}.log"));
        $script = 'set -o pipefail; mkdir -p '.escapeshellarg(storage_path('logs/dev'))
            ." && {$command} 2>&1 | tee -a {$logFile}";

        return 'bash -c '.escapeshellarg($script);
    }
}
